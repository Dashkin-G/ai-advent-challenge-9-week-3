def cost_usd(code: str, prompt_tokens: int, completion_tokens: int) -> float | None:
    """Теоретическая стоимость запроса по тарифу pay-as-you-go (USD).

    None, если цена модели не задана — тогда в интерфейсе показывается «free-квота».
    """
    m = MODEL_BY_CODE.get(code)
    if not m or m["price_in"] is None or m["price_out"] is None:
        return None
    return prompt_tokens / 1e6 * m["price_in"] + completion_tokens / 1e6 * m["price_out"]


