def state_label(code: str) -> str:
    """Русская подпись этапа; для незнакомого кода — сам код."""
    state = TASK_STATE_BY_CODE.get(code)
    return state["label"] if state else code


def state_en(code: str) -> str:
    """Название этапа из задания курса, по-английски (пусто для незнакомого кода)."""
    state = TASK_STATE_BY_CODE.get(code)
    return state["en"] if state else ""


def state_short(code: str) -> str:
    """Короткая подпись этапа для узких колонок."""
    state = TASK_STATE_BY_CODE.get(code)
    return state["short"] if state else code


def state_sections(code: str) -> tuple:
    """Какие части карточки задачи уходят в запрос на этом этапе."""
    state = TASK_STATE_BY_CODE.get(code)
    return tuple(state["sections"]) if state else ()


def state_rule(code: str) -> str:
    """Правило этапа для модели (пусто, если этап ничего не требует)."""
    state = TASK_STATE_BY_CODE.get(code)
    return state["rule"] if state else ""


def state_exit(code: str) -> str:
    """При каком условии этап считается пройденным."""
    state = TASK_STATE_BY_CODE.get(code)
    return state["exit"] if state else ""


def allowed_states(code: str) -> tuple:
    """Куда из этого этапа перейти можно. Всё остальное код отклонит."""
    return tuple(TASK_TRANSITIONS.get(code, ()))


